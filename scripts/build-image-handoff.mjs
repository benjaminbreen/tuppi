// Writes docs/ritual-image-pending.json and docs/RITUAL_IMAGE_PROMPTS.md: every
// visual still pointing at the placeholder, with its prompt, target file and the
// steps that use it, for an image model to fill. Re-run after merging editions.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'src/data/rituals');
const read = (name) => JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
const visuals = read('visual-assets.json'), units = read('units.json'), catalog = read('catalog.json');
const grammar = read('grammar.json');
const usedBy = {};
for (const entry of catalog) {
  const edition = read(`${entry.id}.json`);
  for (const step of edition.steps) {
    const assetId = units[step.unitId]?.visualAssetId;
    (usedBy[assetId] ??= []).push({ ritualId: edition.id, stepId: step.id, title: step.title, summary: step.summary, alt: step.image.alt, note: step.image.note });
  }
}
const STYLE = 'Match the existing tuppi ritual plates in /public/rituals. Genuine alpha transparency; no text or frame.';
const pending = Object.entries(visuals).filter(([, v]) => v.status === 'pending').map(([assetId, v]) => {
  const uses = usedBy[assetId] ?? [];
  return { assetId, subject: v.subject, prompt: `${v.prompt} ${STYLE}`, targetFile: `/rituals/${uses[0]?.ritualId ?? 'misc'}/${assetId}.png`,
    uses: uses.map(({ ritualId, stepId, title, alt, note }) => ({ ritualId, stepId, title, alt, note })) };
});
fs.writeFileSync(path.join(root, 'docs/ritual-image-pending.json'), JSON.stringify(pending, null, 2) + '\n');

const md = [
  '# Ritual image prompts (for GPT-6)',
  '',
  `Generated by \`node scripts/build-image-handoff.mjs\`. ${pending.length} step illustrations still use \`/rituals/_pending.png\`.`,
  '',
  '## How to deliver an image',
  '1. Generate from the prompt; check it against the step\'s actor, object and verb (the `uses` list) before saving. Reject the image if the right materials are shown doing the wrong act.',
  '2. Save a transparent PNG at `public` + `targetFile`.',
  '3. In `src/data/rituals/visual-assets.json`, set that asset\'s `src` to `targetFile`, set `medium` to "AI reconstruction · transparent PNG", and delete `status` and `prompt`.',
  '4. Run `npm run check:rituals` (it verifies the PNG and its alpha channel).',
  '',
  '## Step illustrations',
  '',
  ...pending.flatMap((item) => [
    `### \`${item.assetId}\` — ${item.subject}`,
    `Target: \`public${item.targetFile}\` · used by ${item.uses.map((u) => `${u.ritualId}/${u.stepId}`).join(', ')}`,
    '',
    `> ${item.prompt}`,
    '',
  ]),
  '## Optional: composable sprites for the grammar layer',
  '',
  'Composed recipes recombine acts across rituals, so a card sometimes shows an act applied to a different object (a source-prescribed clay figure being held over a patient). A small sprite set would let a card be drawn as pose + object instead of reusing a source plate. These are optional; the app works without them.',
  '',
  ...Object.entries(grammar.verbs).filter(([verb]) => verb !== 'speak').map(([verb, v]) => `- \`sprites/verb-${verb}.png\` — A plain, generic figure (simple undyed tunic, no culture-specific costume) performing: ${v.gloss}. Hands and target area left empty so an object sprite can be composited in. ${STYLE}`),
  '',
  ...Object.entries(grammar.objectClasses).filter(([c]) => !['person', 'deity', 'harm', 'place', 'materials'].includes(c)).map(([c, gloss]) => `- \`sprites/object-${c}.png\` — ${gloss}: one neutral, isolated example (colour and material variants are tinted in code). ${STYLE}`),
  '',
];
fs.writeFileSync(path.join(root, 'docs/RITUAL_IMAGE_PROMPTS.md'), md.join('\n'));
console.log(`Wrote ${pending.length} pending image prompts.`);
